// IH1 factory preset index (V6): writes docs/FACTORY_PRESETS.md from the bank itself, so it can never go stale again.
// For every preset: intensity, intended sources, style, chain, macro names (with their exact targets in a tooltip-like
// detail list), the latency the chain reports at 48 kHz in Full Quality, whether a feedback loop is present, and the
// output level on its primary source (Output Safety off).
// Usage: ih1_preset_index [out.md]
#include <cmath>
#include <cstdio>
#include <string>
#include <vector>

#include "ih1/engine/Engine.h"
#include "ih1/model/Session.h"
#include "ih1/presets/Audition.h"
#include "ih1/presets/Presets.h"

using namespace ih1;

namespace {
// a recirculating path that the user can hear decay (echo / reverb / feedback controls in use)
std::string feedbackRisk(const FactoryPreset& p) {
    bool loop = false, high = false;
    for (const auto& f : p.chain) {
        const int t = fxTypeIndex(f.type);
        if (t < 0) continue;
        const auto& d = fxRegistry()[static_cast<size_t>(t)];
        auto v = d.defaults();
        for (const auto& [id, x] : f.params) if (d.paramIndex(id) >= 0) v[static_cast<size_t>(d.paramIndex(id))] = x;
        for (size_t i = 0; i < d.params.size(); ++i) {
            const auto& s = d.params[i];
            if (s.id == "feedback" || s.id == "regen" || s.id == "intensity") {
                if (v[i] > 0.0f) loop = true;
                if (s.toNormalised(v[i]) >= 0.7f) high = true;
            }
        }
        if (f.type == "reverb" || f.type == "cloud_chamber" || f.type == "shimmer" || f.type == "drum_space") loop = true;
    }
    return high ? "high (bounded)" : (loop ? "decaying loop" : "none");
}
std::string chainText(const FactoryPreset& p) {
    std::string s;
    for (const auto& f : p.chain) {
        const int t = fxTypeIndex(f.type);
        s += (s.empty() ? "" : " > ") + (t >= 0 ? fxRegistry()[static_cast<size_t>(t)].name : f.type);
    }
    return s;
}
std::string esc(std::string s) {
    for (size_t i = 0; (i = s.find('|', i)) != std::string::npos; i += 2) s.replace(i, 1, "\\|");
    return s;
}
}  // namespace

int main(int argc, char** argv) {
    FILE* out = argc > 1 ? std::fopen(argv[1], "w") : stdout;
    if (!out) return 2;
    const auto& bank = factoryPresets();
    std::fprintf(out, "# IH1 factory presets (0.6.0)\n\n");
    std::fprintf(out, "Generated by `tools/ih1_preset_index.cpp` from `core/src/presets` (%zu presets, Init included). Intensity: Subtle / Moderate / "
                      "Strong / Extreme. **Macros**: the knobs shown beside IN / MIX / OUT when the preset is loaded (host parameters Preset Macro 1-4), "
                      "with their exact targets below each category table. **Latency**: samples the chain reports at 48 kHz in Full Quality. "
                      "**Loop**: none / a decaying echo or reverb loop / high feedback (bounded by design). **Level**: output vs input on the "
                      "preset's first intended source, Output Safety off. The quality screen is `docs/V6_PRESET_AUDIT.md`.\n",
                 bank.size());
    for (const auto& cat : presetCategories()) {
        std::vector<const FactoryPreset*> in;
        for (const auto& p : bank) if (p.category == cat) in.push_back(&p);
        if (in.empty()) continue;
        std::fprintf(out, "\n## %s (%zu)\n\n", cat.c_str(), in.size());
        std::fprintf(out, "| Preset | Intensity | Sources | Style | Chain | Macros | Latency | Loop | Level | What it does |\n");
        std::fprintf(out, "|---|---|---|---|---|---|---|---|---|---|\n");
        std::string details;
        for (const auto* p : in) {
            Engine e;
            Session s(e);
            s.prepare(48000.0, 256);
            const std::string js = presetToJson(*p);
            std::string macros, level = "";
            int latency = 0;
            if (p->id != kInitPresetId && s.fromJson(js, false)) {
                for (size_t m = 0; m < s.macros().size(); ++m) {
                    macros += (macros.empty() ? "" : ", ") + s.macros()[m].name;
                    details += "- *" + p->name + "*: " + s.macroDescription(static_cast<int>(m)) + "\n";
                }
                latency = s.latencySamples();
                const auto r = audition::run(js, audition::sourcesForTags(p->tags).front(), 3.0);
                char b[32];
                std::snprintf(b, sizeof b, "%+.0f dB", r.gainDb);
                level = b;
            }
            std::fprintf(out, "| %s | %s | %s | %s | %s | %s | %d | %s | %s | %s |\n", esc(p->name).c_str(), p->intensity.c_str(), esc(p->tags).c_str(),
                         esc(p->styles).c_str(), esc(chainText(*p)).c_str(), macros.c_str(), latency, p->id == kInitPresetId ? "" : feedbackRisk(*p).c_str(),
                         level.c_str(), esc(p->description).c_str());
        }
        if (!details.empty()) std::fprintf(out, "\nMacro targets:\n%s", details.c_str());
    }
    if (out != stdout) std::fclose(out);
    return 0;
}
